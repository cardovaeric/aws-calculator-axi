export const DEFAULT_REGION = "us-east-1";

/** Parent region for local/Wavelength zones (used as a pricing fallback). */
export function parentRegion(regionCode) {
  if (!regionCode) return null;
  const local = regionCode.replace(/-(?:wl\d.*|[a-z]{2,4}-\d+)$/, "");
  return local !== regionCode && REGION_NAMES[local] ? local : null;
}

export function regionName(regionCode) {
  return REGION_NAMES[regionCode] ?? null;
}

export function resolveRegion(input) {
  if (!input) return DEFAULT_REGION;
  const lower = String(input).toLowerCase();
  if (REGION_NAMES[lower]) return lower;
  const byName = Object.entries(REGION_NAMES).find(
    ([, name]) => name.toLowerCase() === lower,
  );
  return byName ? byName[0] : null;
}
